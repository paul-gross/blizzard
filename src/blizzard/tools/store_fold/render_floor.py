"""Render one store tree's schema and seeded rows, run as a file by a floor release's own interpreter.

    python -I src/blizzard/tools/store_fold/render_floor.py <hub|runner> <store-url>

Imports the release's own store schema module and Alembic, so it depends only on what the floor wheel installs and never
on this checkout. ``<store-url>`` is the SQLite store the release's own ``migrate`` built from an empty one; the
schema is rendered from the release's declared metadata, the rows are read from that store. A store whose tables
differ from the declared ones is refused, since the rendered baseline would then differ from the history.

Prints one JSON document: ``upgrade`` and ``downgrade`` (Alembic operation bodies), ``tables`` (every table that
holds rows, in dependency order, with its rows) and ``sequences`` (the integer autoincrement key of each such
table that has one). A datetime is ``{"$datetime": iso}`` and bytes are ``{"$bytes": base64}``."""

from __future__ import annotations

import base64
import importlib
import json
import sys
from datetime import datetime
from typing import Any, Literal

import sqlalchemy as sa
from alembic.autogenerate import produce_migrations, render_python_code
from alembic.migration import MigrationContext
from sqlalchemy.sql.elements import False_, True_
from sqlalchemy.sql.schema import DefaultClause

_VERSION_TABLE = "alembic_version"
_AUTOGENERATED_MARK = "# ###"


def _render_item(kind: str, obj: Any, autogen_context: Any) -> str | Literal[False]:
    """Alembic renders a column type or a server default by its SQLite compilation; these two must stay portable."""
    if kind == "type" and type(obj).__name__ == "UtcDateTime":
        return "UtcDateTime()"
    if kind == "server_default" and isinstance(obj, DefaultClause) and isinstance(obj.arg, (True_, False_)):
        return "sa.true()" if isinstance(obj.arg, True_) else "sa.false()"
    return False


def _body(ops: Any, context: MigrationContext) -> str:
    code = render_python_code(ops, render_item=_render_item, migration_context=context)
    return "\n".join(line for line in code.splitlines() if not line.strip().startswith(_AUTOGENERATED_MARK))


def _encode(value: Any) -> Any:
    if isinstance(value, datetime):
        return {"$datetime": value.isoformat()}
    if isinstance(value, bytes):
        return {"$bytes": base64.b64encode(value).decode()}
    return value


def _autoincrement_key(table: sa.Table) -> str | None:
    key = list(table.primary_key.columns)
    if len(key) == 1 and isinstance(key[0].type, sa.Integer) and key[0].autoincrement is not False:
        return str(key[0].name)
    return None


def main(tree: str, url: str) -> dict[str, Any]:
    metadata = importlib.import_module(f"blizzard.{tree}.store.schema").metadata
    history = sa.create_engine(url)
    try:
        held = set(sa.inspect(history).get_table_names()) - {_VERSION_TABLE}
        declared = set(metadata.tables)
        if held != declared:
            raise SystemExit(
                f"the {tree} history store and its declared schema disagree on tables: "
                f"only in the store {sorted(held - declared)}, only declared {sorted(declared - held)}"
            )
        tables: dict[str, Any] = {}
        sequences: dict[str, str] = {}
        with history.connect() as connection:
            for table in metadata.sorted_tables:
                rows = [
                    {name: _encode(value) for name, value in row.items()}
                    for row in connection.execute(sa.select(table)).mappings()
                ]
                if rows:
                    tables[table.name] = rows
                    if (key := _autoincrement_key(table)) is not None:
                        sequences[table.name] = key
    finally:
        history.dispose()
    empty = sa.create_engine("sqlite://")
    try:
        with empty.connect() as connection:
            context = MigrationContext.configure(connection)
            operations = produce_migrations(context, metadata)
            return {
                "upgrade": _body(operations.upgrade_ops, context),
                "downgrade": _body(operations.downgrade_ops, context),
                "tables": tables,
                "sequences": sequences,
            }
    finally:
        empty.dispose()


if __name__ == "__main__":
    json.dump(main(sys.argv[1], sys.argv[2]), sys.stdout)
