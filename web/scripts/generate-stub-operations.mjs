// Derives the type-only operation tables the typed spec stubs key on
// (`fleet/src/lib/testing/{hub,runner}-operations.gen.ts`) from the generated
// clients' `types.gen.ts`. Each table maps `'METHOD /templated/url'` to the
// operation's path params, success responses, and declared errors. The method
// comes from the operation name's HTTP suffix; hey-api's `Options` type omits
// the url, so the SDK cannot supply the key.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'projects', 'fleet', 'src', 'lib');
const METHODS = ['Get', 'Post', 'Put', 'Patch', 'Delete'];

function table(plane, interfaceName) {
  const source = readFileSync(join(root, 'api', plane, 'types.gen.ts'), 'utf8');
  const declared = new Set([...source.matchAll(/^export type (\w+) =/gm)].map((m) => m[1]));
  const entries = new Map();
  for (const m of source.matchAll(/^export type (\w+)Data = \{[\s\S]*?^\s+url: '([^']+)';/gm)) {
    const [, op, url] = m;
    const suffix = METHODS.find((s) => op.endsWith(s));
    if (!suffix) throw new Error(`${plane}: operation ${op} has no HTTP-method suffix`);
    const key = `${suffix.toUpperCase()} ${url}`;
    if (entries.has(key)) throw new Error(`${plane}: two operations share the key '${key}'`);
    const ref = (suffixName, fallback) => (declared.has(`${op}${suffixName}`) ? `T.${op}${suffixName}` : fallback);
    entries.set(key, {
      path: `T.${op}Data['path']`,
      responses: ref('Responses', '{}'),
      errors: ref('Errors', '{}'),
    });
  }
  const lines = [...entries.keys()].sort().map((key) => {
    const e = entries.get(key);
    return `  '${key}': { path: ${e.path}; responses: ${e.responses}; errors: ${e.errors} };`;
  });
  return [
    '// Generated by web/scripts/generate-stub-operations.mjs from the plane\'s types.gen.ts — do not edit.',
    `import type * as T from '../api/${plane}/types.gen';`,
    '',
    `export interface ${interfaceName} {`,
    ...lines,
    '}',
    '',
  ].join('\n');
}

writeFileSync(join(root, 'testing', 'hub-operations.gen.ts'), table('hub', 'HubOperations'));
writeFileSync(join(root, 'testing', 'runner-operations.gen.ts'), table('runner', 'RunnerOperations'));
